def _ms(nanoseconds: float) -> str:
    return f"{nanoseconds / 1e6:,.1f} ms"


def _identity_rows(identity: Mapping) -> list:
    wanted = (
        ("machine", "machine"),
        ("CPU", "cpu_sku"),
        ("NPU", "npu_sku"),
        ("NPU driver", "npu_driver_version"),
        ("corelib SHA-256", "corelib_dll_sha256"),
        ("corelib source revision", "corelib_source_revision"),
        ("model SHA-256", "model_sha256"),
        ("FastFlow revision", "fastflow_revision"),
        ("measured (UTC)", "utc"),
    )
    return [
        (label, str(identity[key]))
        for label, key in wanted
        if identity.get(key) is not None
    ]


def build_document_section(
    measurements: Measurements,
    selection: Selection,
    agreement: HistoryReport,
) -> str:
    """Render the Section 15.6 telemetry for the selected constant."""
    winners = measurements.winners_by_history()
    out = []
    add = out.append

    add(_DOCUMENT_BEGIN)
    add("")
    add("## Phi-4 continuation routing — the release-fixed threshold")
    add("")
    add(
        "Design Section 10.7 fixes ONE integer for the release and applies it "
        "at every history length: append when the suffix is at most the "
        "threshold, clear and re-prefill when it is larger. It is a FastFlow "
        "backend constant — not model-package data, not a runtime "
        "calibration — so route choice does not drift with thermal state or "
        "load."
    )
    add("")
    add(f"```cpp")
    add(f"inline constexpr std::uint32_t kContinuationAppendThreshold = "
        f"{selection.threshold};")
    add("```")
    add("")

    if selection.verdict == "selected":
        add(
            f"**Selected: {selection.threshold}.** Suffix lengths "
            f"{list(selection.winners)} are the sampled lengths whose append "
            f"p95 is lower than re-prefill p95 at BOTH measured history "
            f"lengths, and they form a prefix of the sampled set "
            f"{list(selection.ordered)}, so the largest of them is the "
            f"threshold."
        )
    else:
        add(
            f"**Selected: 0 — every prefix hit re-prefills.** "
            + " ".join(selection.diagnostics)
        )
    add("")

    add("### Which sampled lengths append wins, per history")
    add("")
    add("| history rows | append p95 wins at | last winning length |")
    add("| ---: | :--- | ---: |")
    for history in measurements.histories:
        won = winners[history]
        add(
            f"| {history} | {list(won) if won else 'none'} | "
            f"{max(won) if won else 0} |"
        )
    add("")
    add(
        f"The rule is a conjunction, so the constant is the smaller of those "
        f"ceilings. It is NOT a per-history policy: Section 10.7 specifies one "
        f"integer, and one integer cannot be optimal at two history lengths "
        f"whose crossovers differ."
    )
    add("")

    add("### What the single constant gives up")
    add("")
    conceded = {
        history: [s for s in winners[history] if s > selection.threshold]
        for history in measurements.histories
    }
    if any(conceded.values()):
        add(
            "| history rows | suffixes append would have won and now loses | "
            "widest such suffix | append p95 there | re-prefill p95 there | "
            "route taken |"
        )
        add("| ---: | :--- | ---: | ---: | ---: | :--- |")
        for history in measurements.histories:
            given_up = conceded[history]
            if not given_up:
                add(f"| {history} | none | — | — | — | — |")
                continue
            worst = max(given_up)
            add(
                f"| {history} | {given_up} | {worst} | "
                f"{_ms(measurements.point(history, worst, 'append').p95_ns)} | "
                f"{_ms(measurements.point(history, worst, 'reprefill').p95_ns)} | "
                f"re-prefill |"
            )
        add("")
        add(
            "Those are measured losses taken deliberately. The alternative — a "
            "threshold above the smaller ceiling — is optimal for the longer "
            "history and WRONG for the shorter one, where it would append past "
            "the point at which append has already lost. Conceding measured "
            "throughput at one history is the cheaper error than routing "
            "against the measurement at the other."
        )
        add("")
        add(
            "There is a second reason to prefer the smaller ceiling, and it is "
            "about confidence rather than cost. Task 13 measured this crossover "
            "three times and found the bracket's LOWER edge stable across runs "
            "and its UPPER edge not: the upper edge moves with how quiet the "
            "machine was, because that is what decides how many points near the "
            "crossover can be called at all. The threshold selected here sits "
            "at or below the lower edge at every measured history, so it is "
            "inside the append-wins region on every run. A threshold chosen "
            "from the upper edge would be supported by some runs and not "
            "others."
        )
    else:
        add(
            "Nothing. At every measured history length, append wins at no "
            "sampled suffix length beyond the threshold, so the single "
            "constant costs nothing that the measurement can see."
        )
    add("")

    add("### The measurement behind it")
    add("")
    add("| history rows | suffix | append p50 | append p95 | re-prefill p50 | "
        "re-prefill p95 | append p95 wins |")
    add("| ---: | ---: | ---: | ---: | ---: | ---: | :---: |")
    for history in measurements.histories:
        for suffix in measurements.suffixes:
            append = measurements.point(history, suffix, "append")
            reprefill = measurements.point(history, suffix, "reprefill")
            add(
                f"| {history} | {suffix} | {_ms(append.p50_ns)} | "
                f"{_ms(append.p95_ns)} | {_ms(reprefill.p50_ns)} | "
                f"{_ms(reprefill.p95_ns)} | "
                f"{'yes' if append.p95_ns < reprefill.p95_ns else 'no'} |"
            )
    add("")
    add(
        f"At least {MIN_WARM_SAMPLES} warm samples per route per point, "
        f"append and re-prefill interleaved WITHIN each point. p50 and p95 are "
        f"nearest-rank and were recomputed from the raw samples by the "
        f"calibrator, not copied."
    )
    add("")

    add("### Would earlier runs have chosen the same constant?")
    add("")
    add(
        "Each recorded crossover run carries, per history, the bracket "
        "`[lower, upper]`. The lower edge IS that run's per-history winner "
        "ceiling, so the constant is recomputable from every recorded run. "
        "Task 13 measured the lower edges to be stable and the upper edges not; "
        "this derivation touches only the lower edges, which is why an unstable "
        "upper edge does not move the answer."
    )
    add("")
    add("| measured (UTC) | interleaved | would select | agrees with "
        f"{selection.threshold} |")
    add("| --- | :---: | ---: | :---: |")
    for row in agreement.rows:
        if not row.comparable:
            add(
                f"| {row.utc} | no | ({row.derived}) | excluded — routes not "
                f"measured against the same machine state |"
            )
        else:
            add(
                f"| {row.utc} | yes | {row.derived} | "
                f"{'yes' if row.agrees else 'NO'} |"
            )
    add("")
    if agreement.agrees:
        add(
            f"Every interleaved run on record would have selected "
            f"{selection.threshold}."
        )
    else:
        for line in agreement.diagnostics:
            add(f"**{line}**")
    add("")
    add(
        "The non-interleaved rows are shown for provenance and excluded from "
        "the verdict, because their two routes were measured in separate "
        "blocks and a machine regime shift there lands on one route and not "
        "the other. The first of them derives a smaller constant for a reason "
        "that has nothing to do with the machine: it swept only the five "
        "suffix lengths Section 10.7 names, and on `{1, 2, 32, 128, 256}` the "
        "last winning sampled length is 2 whether the true crossover is at 3 "
        "or at 31. **Two earlier answers are withdrawn and must not be "
        "reused: the threshold `2` from that sparse grid, and the "
        "extrapolated figures `≈9 at history 512, ≈26 at history 2048` from a "
        "contended non-interleaved run.** The calibrator therefore treats the "
        "five named lengths as a floor and uses every additional measured "
        "length."
    )
    add("")

    add("### Identity of the run this constant came from")
    add("")
    add("| | |")
    add("| --- | --- |")
    for label, value in _identity_rows(measurements.identity):
        add(f"| {label} | `{value}` |")
    add("")
    add(
        "The timing table above is published here and is NOT shipped in the "
        "model package: Section 10.7 carries the threshold and no cost table."
    )
    add("")
    add(_DOCUMENT_END)
    return "\n".join(out) + "\n"


def apply_section_to_document(source: str, section: str) -> str:
    begin = source.find(_DOCUMENT_BEGIN)
    end = source.find(_DOCUMENT_END)
    if begin != -1 and end != -1:
        return source[:begin] + section.rstrip("\n") + source[end + len(_DOCUMENT_END) :]
    if begin != -1 or end != -1:
        raise CalibrationError("document has an unterminated threshold section")
    prefix = source if source.endswith("\n") else source + "\n"
    return prefix + "\n" + section


