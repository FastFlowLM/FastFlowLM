def _read_json(path: pathlib.Path, what: str):
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        raise CalibrationError(f"cannot read {what} {path}: {error}") from error
    try:
        return json.loads(text)
    except json.JSONDecodeError as error:
        raise CalibrationError(f"{what} {path} is not valid JSON: {error}") from error


def _provenance(measurements: Measurements, selection: Selection) -> list:
    identity = measurements.identity
    return [
        "Generated. Do not edit this block by hand; re-run the calibrator.",
        "",
        "Design Section 10.7: the largest sampled suffix length whose append",
        "p95 is lower than re-prefill p95 at BOTH history lengths "
        f"{list(measurements.histories)},",
        "after asserting the winning lengths are a prefix of the sampled set.",
        "",
        f"verdict:  {selection.verdict}",
        f"winners:  {list(selection.winners)} of sampled {list(selection.ordered)}",
        f"measured: {identity.get('utc', 'unknown')} on "
        f"{identity.get('machine', 'unknown')}",
        f"corelib:  {identity.get('corelib_dll_sha256', 'unknown')}",
        f"model:    {identity.get('model_sha256', 'unknown')}",
    ]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Select the release-fixed Phi-4 continuation threshold.",
    )
    parser.add_argument("--baseline", required=True, type=pathlib.Path)
    parser.add_argument("--crossover-history", required=True, type=pathlib.Path)
    parser.add_argument("--header", required=True, type=pathlib.Path)
    parser.add_argument("--document", required=True, type=pathlib.Path)
    parser.add_argument("--json", type=pathlib.Path, default=None)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the checked-in header and document already match; write "
        "nothing and exit non-zero if they do not",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    try:
        measurements = load_continuation_samples(
            _read_json(args.baseline, "baseline")
        )
        selection = select_threshold_detailed(measurements.samples())
        crossover_notes = measurements.crossover_disagreements(selection)
        records = _read_json(args.crossover_history, "crossover history")
        if not isinstance(records, Sequence) or isinstance(records, (str, bytes)):
            raise CalibrationError("crossover history is not a list of records")
        agreement = history_agreement(records, selection.threshold)

        section = build_document_section(measurements, selection, agreement)
        provenance = _provenance(measurements, selection)

        try:
            header_source = args.header.read_text(encoding="utf-8")
        except OSError as error:
            raise CalibrationError(
                f"cannot read header {args.header}: {error}"
            ) from error
        header_wanted = apply_threshold_to_header(
            header_source, selection.threshold, provenance
        )
        try:
            document_source = args.document.read_text(encoding="utf-8")
        except OSError as error:
            raise CalibrationError(
                f"cannot read document {args.document}: {error}"
            ) from error
        document_wanted = apply_section_to_document(document_source, section)
    except CalibrationError as error:
        print(f"calibration refused: {error}", file=sys.stderr)
        return 2

    for line in selection.diagnostics:
        print(f"diagnostic: {line}", file=sys.stderr)
    for line in crossover_notes:
        print(f"diagnostic: {line}", file=sys.stderr)
    for line in agreement.diagnostics:
        print(f"diagnostic: {line}", file=sys.stderr)

    failed = []
    if crossover_notes:
        failed.append(
            "the Section 10.7 p95 rule contradicts the recorded bracket"
        )
    if not agreement.agrees:
        failed.append("the constant is not supported by every interleaved run")

    stale = []
    if args.check:
        if header_source != header_wanted:
            stale.append(f"{args.header} is stale")
        if document_source != document_wanted:
            stale.append(f"{args.document} is stale")
        for line in stale:
            print(f"stale: {line}", file=sys.stderr)
    else:
        if not failed:
            args.header.write_text(header_wanted, encoding="utf-8", newline="\n")
            args.document.write_text(
                document_wanted, encoding="utf-8", newline="\n"
            )
        else:
            print(
                "refusing to write the header or the document; see the "
                "diagnostics above",
                file=sys.stderr,
            )

    if args.json is not None:
        args.json.write_text(
            json.dumps(
                {
                    "threshold": selection.threshold,
                    "verdict": selection.verdict,
                    "winners": list(selection.winners),
                    "sampled_suffixes": list(selection.ordered),
                    "winners_by_history": {
                        str(history): list(won)
                        for history, won in measurements.winners_by_history().items()
                    },
                    "diagnostics": list(selection.diagnostics)
                    + list(crossover_notes)
                    + list(agreement.diagnostics),
                    "history_agreement": {
                        "comparable": agreement.comparable,
                        "agrees": agreement.agrees,
                        "rows": [
                            dataclasses.asdict(row) for row in agreement.rows
                        ],
                    },
                    "identity": dict(measurements.identity),
                    "checked": bool(args.check),
                    "stale": stale,
                },
                indent=1,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
            newline="\n",
        )

    print(f"threshold = {selection.threshold} ({selection.verdict})")
    if failed or stale:
        return 1
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
