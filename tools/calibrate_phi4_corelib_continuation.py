def percentile_ns(samples: Iterable[float], quantile: float) -> float:
    """Nearest-rank percentile.

    Nearest-rank rather than an interpolating definition because that is what
    the Task 13 recorder used, and this script cross-checks every recorded
    p50/p95 against a recomputation from the raw samples. A different
    definition here would turn that cross-check into noise.
    """
    ordered = sorted(samples)
    if not ordered:
        raise CalibrationError("cannot take a percentile of zero samples")
    if not 0.0 < quantile <= 1.0:
        raise CalibrationError(f"quantile {quantile!r} is outside (0, 1]")
    rank = math.ceil(quantile * len(ordered))
    return ordered[min(len(ordered) - 1, max(0, rank - 1))]


