@dataclasses.dataclass(frozen=True)
class RoutePoint:
    history_rows: int
    suffix: int
    route: str
    count: int
    p50_ns: float
    p95_ns: float


@dataclasses.dataclass(frozen=True)
class Measurements:
    histories: tuple
    suffixes: tuple
    points: Mapping
    identity: Mapping
    recorded_crossover: Mapping
    decision_rule: str

    def point(self, history: int, suffix: int, route: str) -> RoutePoint:
        return self.points[(history, suffix)][route]

    def samples(self) -> dict:
        """The `select_threshold` input, in the per-history shape."""
        return {
            suffix: {
                "per_history": {
                    history: {
                        "append_p95": self.point(history, suffix, "append").p95_ns,
                        "reprefill_p95": self.point(
                            history, suffix, "reprefill"
                        ).p95_ns,
                    }
                    for history in self.histories
                }
            }
            for suffix in self.suffixes
        }

    def winners_by_history(self) -> dict:
        """Per history, the suffix lengths at which append p95 wins."""
        return {
            history: tuple(
                suffix
                for suffix in self.suffixes
                if self.point(history, suffix, "append").p95_ns
                < self.point(history, suffix, "reprefill").p95_ns
            )
            for history in self.histories
        }

    def unclosed_histories(self) -> tuple:
        """Histories whose own winner set is NOT downward-closed.

        Section 10.7 asserts monotonicity of the CONJUNCTION, and that is the
        gate. This is the same property one level down, per history, and it is
        worth checking for two reasons.

        It carries the same meaning: append cost grows with suffix length, so a
        loss at a short suffix followed by a win at a longer one at the SAME
        history is the machine moving during the sweep.

        And it is the exact condition under which `min` over per-history
        ceilings stops equalling the Section 10.7 answer -- the identity the
        cross-run bound in `history_agreement` would need in order to be an
        equality rather than an upper bound. Here the winner sets are known, so
        unlike in a stored crossover record the property can actually be
        checked.
        """
        found = []
        for history, won in self.winners_by_history().items():
            if won != self.suffixes[: len(won)]:
                missing = [s for s in self.suffixes[: len(won)] if s not in won]
                found.append(
                    f"history {history}: append lost at {missing} and won again "
                    f"at a longer suffix; winners {list(won)} are not a prefix "
                    f"of the sampled set {list(self.suffixes)}"
                )
        return tuple(found)

    def crossover_disagreements(self, selection: Selection) -> tuple:
        """Compare the p95 rule against the recorder's own p50-based verdict.

        Task 13's `append_wins_up_to` was decided by a different statistic -- a
        p50 gap that had to clear both the within-point spread and the drift
        across the point. Section 10.7's rule is p95. They should agree; where
        they do not, the constant rests on a statistic the published bracket
        contradicts, and that has to be said rather than resolved silently.
        """
        if not self.recorded_crossover:
            return ()
        found = []
        winners = self.winners_by_history()
        for history in self.histories:
            recorded = self.recorded_crossover.get(str(history))
            if not isinstance(recorded, Mapping):
                continue
            if "append_wins_up_to" not in recorded:
                continue
            declared = recorded["append_wins_up_to"]
            ours = max(winners[history]) if winners[history] else 0
            if declared is None:
                declared = 0
            if declared != ours:
                found.append(
                    f"history {history}: the recorded bracket says append wins "
                    f"up to {declared}, the Section 10.7 p95 rule says {ours}"
                )
        return tuple(found)


def _require_point_fields(raw, index: int) -> RoutePoint:
    where = f"continuation point {index}"
    if not isinstance(raw, Mapping):
        raise CalibrationError(f"{where}: not an object")
    for field in ("history_rows", "suffix", "route", "count", "samples_ns"):
        if field not in raw:
            raise CalibrationError(f"{where}: missing {field!r}")
    history = raw["history_rows"]
    suffix = raw["suffix"]
    if not _is_int(history) or not _is_int(suffix):
        raise CalibrationError(f"{where}: history_rows/suffix must be integers")
    if suffix <= 0 or history <= 0:
        raise CalibrationError(f"{where}: history_rows/suffix must be positive")
    route = raw["route"]
    if route not in ROUTES:
        raise CalibrationError(
            f"{where}: unknown route {route!r}; expected one of {list(ROUTES)}"
        )

    where = f"history {history} suffix {suffix} route {route}"
    samples = raw["samples_ns"]
    if not isinstance(samples, Sequence) or isinstance(samples, (str, bytes)):
        raise CalibrationError(f"{where}: 'samples_ns' is not a list")
    for sample in samples:
        if isinstance(sample, bool) or not isinstance(sample, (int, float)):
            raise CalibrationError(f"{where}: non-numeric sample {sample!r}")
        if sample <= 0:
            raise CalibrationError(f"{where}: non-positive sample {sample!r}")
    if raw["count"] != len(samples):
        raise CalibrationError(
            f"{where}: recorded count {raw['count']} but "
            f"{len(samples)} samples"
        )
    if len(samples) < MIN_WARM_SAMPLES:
        raise CalibrationError(
            f"{where}: {len(samples)} warm samples, Section 10.7 requires at "
            f"least {MIN_WARM_SAMPLES}"
        )

    p50 = percentile_ns(samples, 0.5)
    p95 = percentile_ns(samples, 0.95)
    for field, recomputed in (("p50_ns", p50), ("p95_ns", p95)):
        if field in raw and raw[field] != recomputed:
            raise CalibrationError(
                f"{where}: recorded {field} {raw[field]} does not match the "
                f"nearest-rank value {recomputed} recomputed from samples_ns"
            )
    return RoutePoint(history, suffix, route, len(samples), p50, p95)


def load_continuation_samples(document: Mapping) -> Measurements:
    """Validate a Task 13 baseline document and reduce it to p50/p95 points."""
    if not isinstance(document, Mapping):
        raise CalibrationError("baseline document is not an object")
    block = document.get("continuation")
    if not isinstance(block, Mapping):
        raise CalibrationError("baseline document has no 'continuation' object")

    interleaved = block.get("samples_interleaved")
    if interleaved is not True:
        raise CalibrationError(
            "this record is not marked samples_interleaved=true. Append and "
            "re-prefill measured in separate blocks cannot be compared on a "
            "machine whose throughput has been measured to swing 1.8x between "
            "runs; the first, non-interleaved crossover round was retracted "
            f"for exactly this. Got samples_interleaved={interleaved!r}."
        )

    declared_floor = block.get("warm_samples_per_point")
    if not _is_int(declared_floor) or declared_floor < MIN_WARM_SAMPLES:
        raise CalibrationError(
            f"warm_samples_per_point is {declared_floor!r}; Section 10.7 "
            f"requires at least {MIN_WARM_SAMPLES}"
        )

    raw_points = block.get("points")
    if not isinstance(raw_points, Sequence) or not raw_points:
        raise CalibrationError("'continuation.points' is missing or empty")

    points: dict = {}
    for index, raw in enumerate(raw_points):
        point = _require_point_fields(raw, index)
        bucket = points.setdefault((point.history_rows, point.suffix), {})
        if point.route in bucket:
            raise CalibrationError(
                f"duplicate point: history {point.history_rows} suffix "
                f"{point.suffix} route {point.route} appears more than once"
            )
        bucket[point.route] = point

    histories = sorted({key[0] for key in points})
    unexpected = [h for h in histories if h not in REQUIRED_HISTORIES]
    if unexpected:
        raise CalibrationError(
            f"unexpected history length(s) {unexpected}: Section 10.7's rule is "
            f"a conjunction over exactly {list(REQUIRED_HISTORIES)}, so an "
            f"extra history would change the rule rather than sharpen it"
        )
    missing = [h for h in REQUIRED_HISTORIES if h not in histories]
    if missing:
        raise CalibrationError(
            f"missing required history length(s) {missing}; Section 10.7 "
            f"requires {list(REQUIRED_HISTORIES)}"
        )

    suffixes = sorted({key[1] for key in points})
    missing = [s for s in REQUIRED_SUFFIXES if s not in suffixes]
    if missing:
        raise CalibrationError(
            f"missing required suffix length(s) {missing}; Section 10.7 "
            f"requires at least {list(REQUIRED_SUFFIXES)}"
        )

    for history in REQUIRED_HISTORIES:
        for suffix in suffixes:
            bucket = points.get((history, suffix), {})
            for route in ROUTES:
                if route not in bucket:
                    raise CalibrationError(
                        f"history {history} suffix {suffix}: no {route} point; "
                        f"both routes are needed to compare them"
                    )

    crossover = block.get("crossover")
    return Measurements(
        histories=tuple(sorted(REQUIRED_HISTORIES)),
        suffixes=tuple(suffixes),
        points=points,
        identity=document.get("identity") or {},
        recorded_crossover=crossover if isinstance(crossover, Mapping) else {},
        decision_rule=str(block.get("decision_rule") or ""),
    )


