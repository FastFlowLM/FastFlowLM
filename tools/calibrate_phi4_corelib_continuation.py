# Section 10.7 pins both history lengths. The winner rule is a conjunction over
# this set, so it is required AND exclusive: see the module docstring.
REQUIRED_HISTORIES = (512, 2048)

# Section 10.7 pins these suffix lengths as the measurement grid. They are a
# floor: any additional measured length is used. See the module docstring for
# why -- the five-point grid produced the retracted answer "2".
REQUIRED_SUFFIXES = (1, 2, 32, 128, 256)

MIN_WARM_SAMPLES = 5

ROUTES = ("append", "reprefill")

_HEADER_BEGIN = "// BEGIN generated by tools/calibrate_phi4_corelib_continuation.py"
_HEADER_END = "// END generated by tools/calibrate_phi4_corelib_continuation.py"
_HEADER_DECL = re.compile(
    r"^[ \t]*inline constexpr std::uint32_t kContinuationAppendThreshold"
    r"[ \t]*=[ \t]*\d+[ \t]*;[ \t]*$",
    re.MULTILINE,
)

_DOCUMENT_BEGIN = "<!-- BEGIN phi4-continuation-threshold -->"
_DOCUMENT_END = "<!-- END phi4-continuation-threshold -->"


class CalibrationError(Exception):
    """A record, header or document this script refuses to act on."""


# --------------------------------------------------------------------------
# Statistics
# --------------------------------------------------------------------------


def percentile_ns(samples: Iterable[float], quantile: float) -> float:
    """Nearest-rank percentile.

    Nearest-rank rather than an interpolating definition because that is what
    the Task 13 recorder used, and this script cross-checks every recorded
    p50/p95 against a recomputation from the raw samples. A different
    definition here would turn that cross-check into noise.
    """
    ordered = sorted(samples)
    if not ordered:
        raise CalibrationError("cannot take a percentile of zero samples")
    if not 0.0 < quantile <= 1.0:
        raise CalibrationError(f"quantile {quantile!r} is outside (0, 1]")
    rank = math.ceil(quantile * len(ordered))
    return ordered[min(len(ordered) - 1, max(0, rank - 1))]


