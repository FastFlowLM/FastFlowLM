"""Select the release-fixed Phi-4 continuation append threshold. Task 14.

Design Section 10.7 fixes ONE integer, `kContinuationAppendThreshold`, applied
regardless of history length:

    append when `suffix_tokens <= continuation_append_threshold`; and
    clear plus fresh re-prefill when the suffix is larger.

and it fixes how that integer is chosen:

    the largest suffix length whose append p95 is lower at both history
    lengths, but only after asserting that the set of winning sampled lengths
    is a prefix-contiguous set. If the winners are non-monotonic or none wins,
    the threshold is zero and every prefix hit re-prefills.

This script implements exactly that sentence against the committed Task 13
measurement. Three things about it are worth stating up front, because each is
a place where an obvious implementation would be wrong.

**The conjunction is over histories, and it is not a worst-case reduction.**
"Append p95 is lower at both history lengths" means `append[h] < reprefill[h]`
for every `h`. Collapsing the histories first -- comparing the largest append
p95 against the smallest re-prefill p95 -- is strictly stronger and would
reject suffixes that genuinely win at both.

**The suffix grid is a floor, not a whitelist.** Section 10.7 names suffix
lengths 1, 2, 32, 128 and 256. Task 13 measured that grid and reported the
threshold 2; that answer was retracted, because on `{1, 2, 32, ...}` the last
winning sampled length is 2 whether the true crossover is at 3 or at 31. The
denser 11-point grid Task 13 went on to measure resolves it. So the five named
lengths are REQUIRED to be present and every additional measured length is
USED. Dropping the extra points would faithfully reproduce a retracted answer.
The two history lengths are treated the other way round -- required and
exclusive -- because the conjunction ranges over them, so adding a third would
silently change the rule rather than sharpen it.

**A non-interleaved record is refused outright.** In a non-interleaved run the
two routes are measured in separate blocks, so a machine regime shift lands on
one route and not the other. On the shared lab box that is not hypothetical:
Task 13 measured a 1.8x swing in decode throughput between runs of the same
binary within two hours. The first round of the crossover sweep was
non-interleaved and its answer was retracted. Refusing is not the same as
selecting zero: zero is a measured outcome, and a record that cannot support
any outcome is an input error.

What this script does NOT do, deliberately: it does not emit a per-history
table, a cost model, or anything the runtime consults. Section 10.7 makes the
threshold a release-fixed backend constant, not model-package data and not a
runtime calibration, so the only artefact is one integer in a header.

Usage::

    python -m tools.calibrate_phi4_corelib_continuation \\
        --baseline docs/docs/benchmarks/phi4_aie4_baseline.json \\
        --crossover-history docs/docs/benchmarks/phi4_aie4_crossover_history.json \\
        --header src/include/models/phi4/phi4_corelib_aie4_tuning.hpp \\
        --document docs/docs/benchmarks/phi4_results.md [--check]
"""

from __future__ import annotations

