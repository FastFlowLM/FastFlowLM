def apply_threshold_to_header(
    source: str,
    threshold: int,
    provenance: Sequence[str],
) -> str:
    """Replace the generated threshold block in an existing header.

    The whole file is NOT overwritten. `phi4_corelib_aie4_tuning.hpp` also
    holds `SelectContinuationRoute`, `ContinuationRoute` and
    `ForcedContinuationRoute`, all hand-written and all depended on by the
    frontend; regenerating the file wholesale would delete them. Only the
    declaration, and the marker block around it, are generated.
    """
    if not _is_int(threshold) or threshold < 0:
        raise CalibrationError(f"threshold {threshold!r} is not a non-negative int")

    lines = [_HEADER_BEGIN, "//"]
    # `f"// {line}"` on a blank provenance line would leave trailing
    # whitespace, which some editors and hooks strip -- and a stripped file
    # would then fail `--check` for a reason that has nothing to do with the
    # measurement.
    lines += [f"// {line}".rstrip() for line in provenance]
    lines.append(
        f"inline constexpr std::uint32_t kContinuationAppendThreshold "
        f"= {threshold};"
    )
    lines.append(_HEADER_END)
    block = "\n".join(lines)

    begin = source.find(_HEADER_BEGIN)
    end = source.find(_HEADER_END)
    if begin != -1 and end != -1:
        if source.count(_HEADER_BEGIN) != 1 or source.count(_HEADER_END) != 1:
            raise CalibrationError("header has more than one generated block")
        return source[:begin] + block + source[end + len(_HEADER_END) :]
    if begin != -1 or end != -1:
        raise CalibrationError("header has an unterminated generated block")

    matches = _HEADER_DECL.findall(source)
    if not matches:
        raise CalibrationError(
            "header has no 'inline constexpr std::uint32_t "
            "kContinuationAppendThreshold = <n>;' declaration to replace"
        )
    if len(matches) > 1:
        raise CalibrationError(
            f"header declares kContinuationAppendThreshold {len(matches)} times"
        )
    return _HEADER_DECL.sub(lambda _: block, source, count=1)


