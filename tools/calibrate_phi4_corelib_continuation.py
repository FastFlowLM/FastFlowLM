@dataclasses.dataclass(frozen=True)
class Selection:
    threshold: int
    verdict: str
    winners: tuple
    ordered: tuple
    diagnostics: tuple


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _number(entry: Mapping, key: str, where: str) -> float:
    if key not in entry:
        raise CalibrationError(f"{where}: missing {key!r}")
    value = entry[key]
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise CalibrationError(f"{where}: {key!r} is not a number: {value!r}")
    return float(value)


def _entry_wins(suffix, entry: Mapping) -> bool:
    """Does append beat re-prefill at EVERY history recorded for `suffix`?

    Two entry shapes are accepted and they must not be mixed:

      * `{"append_p95": x, "reprefill_p95": y}` -- one history; and
      * `{"per_history": {h: {"append_p95": x, "reprefill_p95": y}, ...}}`.

    The comparison is strict. Section 10.7 says append p95 must be LOWER, so a
    tie is not a win and routes to re-prefill.
    """
    where = f"suffix {suffix}"
    if not isinstance(entry, Mapping):
        raise CalibrationError(f"{where}: sample entry is not a mapping")
    flat = "append_p95" in entry or "reprefill_p95" in entry
    nested = "per_history" in entry
    if flat and nested:
        raise CalibrationError(
            f"{where}: entry mixes the flat and per-history shapes; pick one"
        )
    if not flat and not nested:
        raise CalibrationError(
            f"{where}: entry has neither 'append_p95'/'reprefill_p95' nor "
            f"'per_history'"
        )
    if flat:
        return _number(entry, "append_p95", where) < _number(
            entry, "reprefill_p95", where
        )

    per_history = entry["per_history"]
    if not isinstance(per_history, Mapping) or not per_history:
        raise CalibrationError(f"{where}: 'per_history' is empty")
    return all(
        _number(measured, "append_p95", f"{where} history {history}")
        < _number(measured, "reprefill_p95", f"{where} history {history}")
        for history, measured in sorted(per_history.items())
    )


def select_threshold_detailed(samples: Mapping) -> Selection:
    """Apply the Section 10.7 rule and say which branch it took.

    Verdicts: `empty`, `no_winner`, `non_monotonic`, `selected`. The first
    three all yield threshold zero -- every prefix hit re-prefills -- and only
    `non_monotonic` is a signal that something is wrong. With an unstable
    upper bracket edge, a non-prefix winner set says the machine moved during
    the sweep, not that append got faster at a longer suffix than a shorter
    one.
    """
    for suffix in samples:
        if not _is_int(suffix):
            raise CalibrationError(f"suffix length {suffix!r} is not an integer")
        if suffix <= 0:
            raise CalibrationError(f"suffix length {suffix!r} is not positive")

    ordered = tuple(sorted(samples))
    if not ordered:
        return Selection(
            0,
            "empty",
            (),
            (),
            ("no sampled suffix lengths; every prefix hit re-prefills",),
        )

    winners = tuple(suffix for suffix in ordered if _entry_wins(suffix, samples[suffix]))
    if not winners:
        return Selection(
            0,
            "no_winner",
            (),
            ordered,
            (
                "append p95 beat re-prefill p95 at no sampled suffix length; "
                "every prefix hit re-prefills",
            ),
        )

    prefix = ordered[: len(winners)]
    if winners != prefix:
        losses = [suffix for suffix in prefix if suffix not in winners]
        late = [suffix for suffix in winners if suffix not in prefix]
        return Selection(
            0,
            "non_monotonic",
            winners,
            ordered,
            (
                "the winning suffix lengths are not a prefix of the sampled "
                f"set: append lost at {losses} and then won again at {late}. "
                "Append cost grows with suffix length, so this is the machine "
                "moving during the sweep, not a real re-crossing. Threshold "
                "is zero and every prefix hit re-prefills.",
            ),
        )

    return Selection(int(max(winners)), "selected", winners, ordered, ())


def select_threshold(samples: Mapping) -> int:
    """The Section 10.7 rule, as one integer."""
    return select_threshold_detailed(samples).threshold


